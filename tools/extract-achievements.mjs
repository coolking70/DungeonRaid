#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const XML = 'reverse/apktool/res/raw/openfeint_offline_config.xml';
export const JAVA = 'reverse/jadx/sources/com/fireflame/dungeonraid/DungeonRaidSurfaceView.java';
const WRAPPER = 'reverse/jadx/sources/com/fireflame/dungeonraid/wrappers/Achievement.java';
const read = p => readFileSync(resolve(root,p),'utf8');
const line = (s,i) => s.slice(0,i).split('\n').length;
const decode = s => s.replace(/&(#x[\da-f]+|#\d+|amp|lt|gt|quot|apos);/gi, (_,v) => v[0]==='#'?String.fromCodePoint(v[1]==='x'?parseInt(v.slice(2),16):Number(v.slice(1))):({amp:'&',lt:'<',gt:'>',quot:'"',apos:"'"})[v]);
export function extractAchievements() {
  const xml=read(XML), java=read(JAVA), wrapper=read(WRAPPER);
  const mapping=/mAchievements = \{([^}]+)\}/.exec(java);
  const ids=[...mapping[1].matchAll(/"([^"]*)"/g)].map(m=>m[1]);
  const enums=[...wrapper.matchAll(/public static final Achievement (ACH_\w+) = new Achievement/g)].map(m=>m[1]);
  if(ids.length!==78||enums.length!==78||ids[0]!==''||enums[0]!=='ACH_NONE')throw Error('Achievement enum/mapping changed');
  function rows(tag,fields){return [...xml.matchAll(new RegExp(`<${tag}>([\\s\\S]*?)</${tag}>`,'g'))].map(m=>{
    const out={}, fieldLines={};
    for(const field of fields){const f=new RegExp(`<${field}>([\\s\\S]*?)</${field}>`).exec(m[0]);if(!f)throw Error(`Missing ${field}`);out[field]=decode(f[1]);fieldLines[field]=line(xml,m.index+f.index);}
    out.source={xml:XML,xmlLine:line(xml,m.index),fieldLines};return out;
  });}
  const achievements=rows('achievement',['id','title','description','gamerscore','is_secret','position']).map(a=>{
    const enumValue=ids.indexOf(a.id);if(enumValue<1)throw Error(`Unmapped achievement ${a.id}`);
    return {...a,enumValue,enumName:enums[enumValue],gamerscore:Number(a.gamerscore),is_secret:a.is_secret==='true',position:Number(a.position),source:{...a.source,java:JAVA,javaLine:line(java,mapping.index),javaIndex:enumValue,wrapper:WRAPPER}};
  }).sort((a,b)=>a.enumValue-b.enumValue);
  if(achievements.length!==77||new Set(achievements.map(a=>a.enumValue)).size!==77)throw Error('Incomplete achievements');
  // Java score-submission branches 425–446; native ScoreScreen categories 0…5.
  const categories={'616324':1,'616344':2,'616364':3,'712357':4,'712367':5};
  const leaderboards=rows('leaderboard',['id','name','position']).map(b=>({...b,position:Number(b.position),category:categories[b.id]??null,source:{...b.source,java:JAVA,javaLine:line(java,java.indexOf(`new Leaderboard("${b.id}")`))}}));
  if(leaderboards.length!==8)throw Error('Incomplete leaderboards');
  return {_source:`${XML}; ${JAVA}:58 mAchievements; ${WRAPPER}. Generated by tools/extract-achievements.mjs.`,schemaVersion:1,sentinel:{enumValue:0,enumName:enums[0],openFeintId:ids[0]},achievements,leaderboards};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const result=extractAchievements();writeFileSync(resolve(root,'data/achievements.json'),JSON.stringify(result,null,2)+'\n');console.log('Extracted 77 achievements, 8 leaderboards; enum 0 is the empty sentinel.');
}
